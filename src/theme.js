export function createDesignTheme(dark = false) {
  return createTheme({
    palette: {
      mode: dark ? 'dark' : 'light',
      primary: {main: dark ? '#a7c99c' : '#42634d'},
      background: {default: dark ? '#181c19' : '#f6f5f1', paper: dark ? '#242b25' : '#fcfcf9'},
      text: {primary: dark ? '#e2e8dc' : '#242b26', secondary: dark ? '#adb7a5' : '#797e78'}
    },
    typography: {fontFamily: 'Inter, ui-sans-serif, -apple-system, BlinkMacSystemFont, \"Segoe UI\", sans-serif', button: {textTransform: 'none', fontWeight: 600}},
    shape: {borderRadius: 10},
    components: {
      MuiCssBaseline: {styleOverrides: {':root': {...(dark ? darkTokens : lightTokens), colorScheme: dark ? 'dark' : 'light'}}},
      MuiButton: {defaultProps: {disableElevation: true}},
      MuiTextField: {defaultProps: {size: 'small'}},
      MuiIconButton: {defaultProps: {size: 'small'}}
    }
  });
}
